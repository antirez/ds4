#!/usr/bin/env python3
"""Regenerate ds4_qwen4_unicode.inc, the codepoint classes of the Qwen3.8
("qwen35") pre-tokenizer regex, from the `regex` module's Unicode tables.
Use a current `regex` release; the generated header records its version.

Usage: python gen_qwen4_unicode.py > ../ds4_qwen4_unicode.inc
       python gen_qwen4_unicode.py minimax > ../ds4_minimax3_unicode.inc
The second form writes the cased letter classes of the MiniMax-M3 ("minimax-m2",
o200k-style) regex; it reuses ds4_qwen4_urange and the classes above.
"""
import sys

import regex

CLASSES = {
    "letter": r"\p{L}",
    "mark": r"\p{M}",
    "number": r"\p{N}",
    "space": r"\s",
}

MINIMAX_CLASSES = {
    "upper": r"[\p{Lu}\p{Lt}\p{Lm}\p{Lo}\p{M}]",
    "lower": r"[\p{Ll}\p{Lm}\p{Lo}\p{M}]",
}


def main() -> None:
    out = sys.stdout
    minimax = sys.argv[1:] == ["minimax"]
    classes, prefix = (MINIMAX_CLASSES, "ds4_minimax3") if minimax else (CLASSES, "ds4_qwen4")
    out.write("/* Generated by gguf-tools/gen_qwen4_unicode.py from the `regex` module's\n")
    out.write(f" * Unicode tables (regex {regex.__version__}); codepoint classes for the\n")
    out.write(" * MiniMax-M3 pre-tokenizer. */\n\n" if minimax else " * Qwen3.8 pre-tokenizer. */\n\n")
    if not minimax:
        out.write("typedef struct { uint32_t lo, hi; } ds4_qwen4_urange;\n\n")
    for index, (name, cls) in enumerate(classes.items()):
        if index:
            out.write("\n")
        pat = regex.compile(cls, regex.V1)
        ranges = []
        lo = prev = None
        for cp in range(0x110000):
            m = False if 0xD800 <= cp <= 0xDFFF else pat.match(chr(cp)) is not None
            if m:
                if lo is None:
                    lo = cp
                prev = cp
            elif lo is not None:
                ranges.append((lo, prev))
                lo = None
        if lo is not None:
            ranges.append((lo, prev))
        out.write(f"static const ds4_qwen4_urange {prefix}_{name}_ranges[] = {{\n")
        for i in range(0, len(ranges), 4):
            out.write("    " + " ".join(f"{{0x{a:05x}, 0x{b:05x}}}," for a, b in ranges[i:i + 4]) + "\n")
        out.write("};\n")


if __name__ == "__main__":
    main()
