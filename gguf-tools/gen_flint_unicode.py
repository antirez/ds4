#!/usr/bin/env python3
"""Regenerate ds4_flint_unicode.inc, the codepoint classes of the Recursive
Flint pre-tokenizer (fork-owned; the Qwen generator is the template).

Flint's third split is the GPT-4o word pattern, which distinguishes upper
and lower case letters, and its punctuation run is \\p{P}\\p{S} rather than
"anything else".  Whitespace is the Unicode White_Space property, which is
what the HF `tokenizers` regex engine (Oniguruma) means by \\s; the `regex`
module's own \\s additionally contains U+001C..U+001F.

Usage: python gen_flint_unicode.py > ../ds4_flint_unicode.inc
"""
import sys

import regex

CLASSES = {
    "letter": r"\p{L}",
    "number": r"\p{N}",
    "mark": r"\p{M}",
    "space": r"\p{White_Space}",
    "upper": r"[\p{Lu}\p{Lt}]",
    "lower": r"\p{Ll}",
    "lother": r"[\p{Lm}\p{Lo}]",
    "punct": r"[\p{P}\p{S}]",
}


def main() -> None:
    out = sys.stdout
    out.write("/* Generated by gguf-tools/gen_flint_unicode.py from the `regex` module's\n")
    out.write(f" * Unicode tables (regex {regex.__version__}); codepoint classes for the\n")
    out.write(" * Recursive Flint pre-tokenizer (fork-owned). */\n\n")
    out.write("typedef struct { uint32_t lo, hi; } ds4_flint_urange;\n\n")
    for index, (name, cls) in enumerate(CLASSES.items()):
        if index:
            out.write("\n")
        pat = regex.compile(cls, regex.V1)
        ranges = []
        lo = prev = None
        for cp in range(0x110000):
            m = False if 0xD800 <= cp <= 0xDFFF else pat.match(chr(cp)) is not None
            if m:
                if lo is None:
                    lo = cp
                prev = cp
            elif lo is not None:
                ranges.append((lo, prev))
                lo = None
        if lo is not None:
            ranges.append((lo, prev))
        out.write(f"static const ds4_flint_urange ds4_flint_{name}_ranges[] = {{\n")
        for i in range(0, len(ranges), 4):
            out.write("    " + " ".join(f"{{0x{a:05x}, 0x{b:05x}}}," for a, b in ranges[i:i + 4]) + "\n")
        out.write("};\n")


if __name__ == "__main__":
    main()
