static float f16_to_f32(uint16_t h) {
    const uint32_t sign = (uint32_t)(h >> 15) << 31;
    const uint32_t exp = (h >> 10) & 0x1f;
    const uint32_t man = h & 0x3ff;
    uint32_t bits;
    if (exp == 0) {
        bits = sign | (man ? (113u << 23) : 0);
        if (man) {
            float v;
            bits = sign;
            v = (float)man * 0x1.0p-24f;
            memcpy(&bits, &v, sizeof(bits));
            bits |= sign;
        }
    } else if (exp == 31) {
        bits = sign | (0xffu << 23) | (man << 13);
    } else {
        bits = sign | ((exp + 112) << 23) | (man << 13);
    }
    float out;
    memcpy(&out, &bits, sizeof(out));
    return out;
}

/* Copy of ds4.c ds4_vec_dot_iq1_s_q8_K. */
static void vec_dot_iq1_s_q8_K(int n, float *s, const block_iq1_s *x, const block_q8_K *y) {
    const int nb = n / QK_K;
    float sumf = 0.0f;
    for (int i = 0; i < nb; i++) {
        const float d = f16_to_f32(x[i].d) * y[i].d;
        const int8_t *q8 = y[i].qs;
        float bsum = 0.0f;
        for (int ib = 0; ib < QK_K / 32; ib++) {
            const uint16_t qh = x[i].qh[ib];
            const float dl = (float)(2 * ((qh >> 12) & 7) + 1);
            const float delta = (qh & 0x8000) ? -IQ1S_DELTA : IQ1S_DELTA;
            int32_t sumi = 0;
            for (int l = 0; l < 4; l++) {
                const int8_t *grid = (const int8_t *)(iq1s_grid + (x[i].qs[4 * ib + l] | (((qh >> (3 * l)) & 7) << 8)));
                for (int j = 0; j < 8; j++) {
                    sumi += (int32_t)grid[j] * (int32_t)q8[32 * ib + 8 * l + j];
                }
            }
            bsum += dl * ((float)sumi + delta * (float)(y[i].bsums[2 * ib] + y[i].bsums[2 * ib + 1]));
        }
        sumf += d * bsum;
    }
    *s = sumf;
}

/* ggml dequantize_row_iq1_s, one block, in double. */
static void reference_dequant_block(const block_iq1_s *x, double *y) {
    const double d = (double)f16_to_f32(x->d);
    const uint8_t *qs = x->qs;
    for (int ib = 0; ib < QK_K / 32; ib++) {
        const double dl = d * (double)(2 * ((x->qh[ib] >> 12) & 7) + 1);
        const double delta = (x->qh[ib] & 0x8000) ? -0.125 : 0.125;
        for (int l = 0; l < 4; l++) {
            const int8_t *grid = (const int8_t *)(iq1s_grid + (qs[l] | (((x->qh[ib] >> (3 * l)) & 7) << 8)));
            for (int j = 0; j < 8; j++) {
                *y++ = dl * ((double)grid[j] + delta);
            }
        }
        qs += 4;
    }
}

static void fill_q8_k(block_q8_K *y, float d, const int8_t *qs) {
    y->d = d;
    memcpy(y->qs, qs, QK_K);
    for (int i = 0; i < QK_K / 16; i++) {
        int sum = 0;
        for (int j = 0; j < 16; j++) sum += qs[16 * i + j];
        y->bsums[i] = (int16_t)sum;
    }
}

static uint32_t rng_state = 0x12345678u;
static uint32_t rnd(void) {
    rng_state = rng_state * 1664525u + 1013904223u;
    return rng_state >> 8;
}

static int test_block_layout(void) {
    const int ok = sizeof(block_iq1_s) == 50;
    printf("  block size: %zu (expect 50): %s\n", sizeof(block_iq1_s), ok ? "PASS" : "FAIL");
    return !ok;
}

static int test_worked_example(void) {
    block_iq1_s x;
    double w[QK_K];
    memset(&x, 0, sizeof(x));
    x.d = 0x3c00; /* 1.0f */
    x.qh[0] = 0x2000; /* s=2, delta +, grid high bits 0; qs[0]=0 -> entry 0 (all -1) */
    reference_dequant_block(&x, w);
    int ok = w[0] == -4.375 && w[7] == -4.375;
    x.qs[1] = 0xff; /* entry 255 low byte; only checks pipeline runs */
    printf("  worked example: %.3f %.3f (expect -4.375 -4.375): %s\n", w[0], w[7], ok ? "PASS" : "FAIL");
    return !ok;
}

static int test_zero_block(void) {
    block_iq1_s x;
    block_q8_K y;
    int8_t qs[QK_K];
    memset(&x, 0, sizeof(x));
    for (int i = 0; i < QK_K; i++) qs[i] = (int8_t)(i - 128);
    fill_q8_k(&y, 0.01f, qs);
    float s = 1.0f;
    vec_dot_iq1_s_q8_K(QK_K, &s, &x, &y);
    const int ok = s == 0.0f;
    printf("  zero block dot: %.1f (expect 0.0): %s\n", s, ok ? "PASS" : "FAIL");
    return !ok;
}

static int test_random_reference(void) {
    enum { N_BLOCK = 8, N = N_BLOCK * QK_K };
    block_iq1_s x[N_BLOCK];
    block_q8_K y[N_BLOCK];
    int8_t qs[QK_K];
    double ref = 0.0;
    for (int b = 0; b < N_BLOCK; b++) {
        uint8_t *raw = (uint8_t *)&x[b];
        for (size_t i = 0; i < sizeof(x[b]); i++) raw[i] = (uint8_t)rnd();
        x[b].d = (uint16_t)(0x3400 + (rnd() & 0x3ff)); /* small positive scale */
        for (int i = 0; i < QK_K; i++) qs[i] = (int8_t)((int)(rnd() & 0xff) - 128);
        fill_q8_k(&y[b], 0.005f, qs);
        double w[QK_K];
        reference_dequant_block(&x[b], w);
        for (int i = 0; i < QK_K; i++) ref += w[i] * ((double)qs[i] * 0.005);
    }
    float got = 0.0f;
    vec_dot_iq1_s_q8_K(N, &got, x, y);
    const double rel = fabs(got - ref) / (fabs(ref) > 1.0 ? fabs(ref) : 1.0);
    const int ok = rel <= 1e-4;
    printf("  random dot vs dequant reference: got %.6f ref %.6f rel %.2e: %s\n",
           got, ref, rel, ok ? "PASS" : "FAIL");
    return !ok;
}

int main(void) {
    int failed = 0;
    failed += test_block_layout();
    failed += test_worked_example();
    failed += test_zero_block();
    failed += test_random_reference();
    printf("%s\n", failed ? "FAIL" : "PASS");
    return failed != 0;
}
