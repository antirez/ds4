#!/usr/bin/env python3
"""Regenerate tests/joyai_pretokenizer_vectors.inc, the expected DeepSeek V4
("joyai-llm") pre-tokenizer pieces, from the official Hugging Face tokenizer.

Usage:
    python gen_joyai_pretokenizer_vectors.py TOKENIZER_JSON > joyai_pretokenizer_vectors.inc

TOKENIZER_JSON is tokenizer.json from deepseek-ai/DeepSeek-V4-Flash (V4.1
Flash ships the same pre-tokenizer).  Needs the `tokenizers` package.

Only regenerating the vectors needs these: the generated file is committed,
so building ds4 and running `make test-joyai-pretokenizer` need neither
Python nor network access.
"""
import random
import sys

import tokenizers
from tokenizers import Tokenizer

CASES = [
    # antirez/ds4#1255
    "以下內容：\n今天天氣晴朗，",
    "22。   多個空白   然後",
    # punctuation and symbols outside ASCII
    "你好，world！ok",
    "他说：“你好”。\n",
    "foo —\nbar – baz",
    "wait… what",
    "a → b →→ c",
    "(“quoted”) and 《书名》、",
    "hello 😀 world😀!",
    "price: 5€, 10£\n",
    # letters, marks and scripts that are not CJK
    "perché è così, città.",
    "Привет, мир!\n",
    "안녕하세요 세계",
    "e\u0301te\u0301 cafe\u0301",
    "\u0301\u0301 marks",
    "使用Python编程和C语言",
    "ひらがな カタカナ ﾊﾝｶｸ",
    "多・多 1・多 カ゠カ ゛゜ ア゛ア゛ x・\n",
    # the last split also runs inside CJK runs: unassigned and combining
    # codepoints of the kana ranges
    "ア぀",
    "か゗か",
    "龥぀ー",
    "か゗゘か",
    "゙か゚か",
    # numbers
    "1234567 and 12",
    "１２３４ full width",
    "a1b22c333d4444",
    "Ⅻ ½ ²³ ٣٤٥",
    # whitespace
    "    int x;\n",
    "  \n\n  x",
    "a\xa0b\u3000c",
    "第一\u3000\u3000第二",
    "x \u2028 y",
    "tab\tbefore\t\tword",
    "trailing   ",
    "\r\n\r\n",
    "。  \n  多",
    # controls no alternative matches
    "a\x01\x02b",
    "\x1c\x1d text",
    # code
    "def f(x):\n    return x + 1;\n",
    "if (a->b && !c) { y = z[0]; }\n",
    "<|tag|>{\"key\": [1, 2]}\n",
]

PIECES = [
    "今天", "世界", "多", "abc", "Python", "é", "x", " ", "  ", "   ", "\n", "\n\n",
    "\t", "：", "，", "。", "！", "“", "”", "《", "》", "、", "…", "—", "1", "22",
    "1234", "１", "(", ")", ":", ";", ".", "<", ">", "_", "😀", "→", "안녕",
    "Привет", "\u3000", "\xa0", "\r\n", "\u0301", "ﾊ", "Ⅻ", "\x01",
]


def byte_decoder():
    bs = list(range(ord("!"), ord("~") + 1)) + list(range(0xa1, 0xad)) + list(range(0xae, 0x100))
    cs = bs[:]
    n = 0
    for b in range(256):
        if b not in bs:
            bs.append(b)
            cs.append(256 + n)
            n += 1
    return {chr(c): b for b, c in zip(bs, cs)}


def c_string(data):
    out = []
    for b in data:
        if b in (0x22, 0x5c, 0x3f):
            out.append("\\" + chr(b))
        elif 0x20 <= b < 0x7f:
            out.append(chr(b))
        else:
            out.append(f"\\{b:03o}")
    return '"' + "".join(out) + '"'


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    pre = Tokenizer.from_file(sys.argv[1]).pre_tokenizer
    decode = byte_decoder()
    rng = random.Random(1255)
    cases = CASES + ["".join(rng.choice(PIECES) for _ in range(rng.randint(2, 10)))
                     for _ in range(200)]

    out = sys.stdout
    out.write("/* Generated by tests/gen_joyai_pretokenizer_vectors.py from the official\n")
    out.write(f" * DeepSeek V4 Flash tokenizer.json (tokenizers {tokenizers.__version__});\n")
    out.write(" * do not edit. */\n\n")
    out.write("static const joyai_vector joyai_vectors[] = {\n")
    for text in cases:
        # the C test measures inputs with strlen()
        assert "\0" not in text
        pieces =[bytes(decode[ch] for ch in piece) for piece, _ in pre.pre_tokenize_str(text)]
        assert b"".join(pieces) == text.encode()
        out.write(f"    {{ {c_string(text.encode())},\n")
        out.write("      (const char *const[]){ ")
        out.write(", ".join(c_string(p) for p in pieces))
        out.write(", NULL } },\n")
    out.write("};\n")


if __name__ == "__main__":
    main()
