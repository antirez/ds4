/* ---- helpers ---- */

static int nearest_centroid(float val) {
    int best = 0;
    float best_d = fabsf(val - DS4_PLANAR3_CENTROIDS[0]);
    for (int i = 1; i < 8; i++) {
        float d = fabsf(val - DS4_PLANAR3_CENTROIDS[i]);
        if (d < best_d) { best_d = d; best = i; }
    }
    return best;
}

/* ---- quantize one 128-dim sub-block ---- */

static void quantize_block_128(const float *src, ds4_block_planar3 *blk, int rot_offset) {
    float norm_sq = 0.0f;
    for (int j = 0; j < DS4_PLANAR3_BLOCK_DIM; j++)
        norm_sq += src[j] * src[j];
    float grp_norm = sqrtf(norm_sq);
    float inv_norm = (grp_norm > 1e-10f) ? 1.0f / grp_norm : 0.0f;

    memset(blk->qs, 0, DS4_PLANAR3_BLOCK_DIM / 4);
    memset(blk->signs, 0, DS4_PLANAR3_BLOCK_DIM / 8);

    float recon_sq = 0.0f;
    const int n_pairs = DS4_PLANAR3_BLOCK_DIM / 2;

    for (int p = 0; p < n_pairs; p++) {
        float v0 = src[p * 2]     * inv_norm;
        float v1 = src[p * 2 + 1] * inv_norm;

        float c = DS4_PLANAR3_COS[rot_offset + p];
        float s = DS4_PLANAR3_SIN[rot_offset + p];
        float r0 = c * v0 - s * v1;
        float r1 = s * v0 + c * v1;

        int idx0 = nearest_centroid(r0);
        int idx1 = nearest_centroid(r1);

        int j0 = p * 2;
        int j1 = p * 2 + 1;

        blk->qs[j0 / 4]     |= (uint8_t)((idx0 & 0x3) << ((j0 % 4) * 2));
        if (idx0 & 0x4) blk->signs[j0 / 8] |= (uint8_t)(1 << (j0 % 8));

        blk->qs[j1 / 4]     |= (uint8_t)((idx1 & 0x3) << ((j1 % 4) * 2));
        if (idx1 & 0x4) blk->signs[j1 / 8] |= (uint8_t)(1 << (j1 % 8));

        recon_sq += DS4_PLANAR3_CENTROIDS[idx0] * DS4_PLANAR3_CENTROIDS[idx0]
                  + DS4_PLANAR3_CENTROIDS[idx1] * DS4_PLANAR3_CENTROIDS[idx1];
    }

    float recon_norm = sqrtf(recon_sq);
    float corrected = (recon_norm > 1e-10f) ? grp_norm / recon_norm : grp_norm;
    blk->norm = fp32_to_fp16(corrected);
}

/* ---- dequantize one 128-dim sub-block ---- */

static void dequantize_block_128(const ds4_block_planar3 *blk, float *dst, int rot_offset) {
    float norm = fp16_to_fp32(blk->norm);
    const int n_pairs = DS4_PLANAR3_BLOCK_DIM / 2;

    for (int p = 0; p < n_pairs; p++) {
        int j0 = p * 2;
        int j1 = p * 2 + 1;

        uint8_t low0 = (blk->qs[j0 / 4]     >> ((j0 % 4) * 2)) & 0x3;
        uint8_t hi0  = (blk->signs[j0 / 8]   >> (j0 % 8))       & 0x1;
        uint8_t idx0 = low0 | (hi0 << 2);

        uint8_t low1 = (blk->qs[j1 / 4]     >> ((j1 % 4) * 2)) & 0x3;
        uint8_t hi1  = (blk->signs[j1 / 8]   >> (j1 % 8))       & 0x1;
        uint8_t idx1 = low1 | (hi1 << 2);

        float q0 = DS4_PLANAR3_CENTROIDS[idx0];
        float q1 = DS4_PLANAR3_CENTROIDS[idx1];

        float c = DS4_PLANAR3_COS[rot_offset + p];
        float s = DS4_PLANAR3_SIN[rot_offset + p];
        float f0 =  c * q0 + s * q1;
        float f1 = -s * q0 + c * q1;

        dst[j0] = f0 * norm;
        dst[j1] = f1 * norm;
    }
}

/* ---- public API ---- */

size_t ds4_planar3_quantize_row(const float *src, ds4_row_planar3 *dst) {
    for (int b = 0; b < DS4_PLANAR3_BLOCKS_512; b++) {
        quantize_block_128(
            src  + b * DS4_PLANAR3_BLOCK_DIM,
            &dst->blocks[b],
            b * (DS4_PLANAR3_BLOCK_DIM / 2)
        );
    }
    return sizeof(ds4_row_planar3);
}

void ds4_planar3_dequantize_row(const ds4_row_planar3 *src, float *dst) {
    for (int b = 0; b < DS4_PLANAR3_BLOCKS_512; b++) {
        dequantize_block_128(
            &src->blocks[b],
            dst + b * DS4_PLANAR3_BLOCK_DIM,
            b * (DS4_PLANAR3_BLOCK_DIM / 2)
        );
    }
}

size_t ds4_planar3_quantize(const float *src, void *dst,
                             size_t nrows, size_t n_per_row) {
    assert(n_per_row == 512);
    size_t total = 0;
    for (size_t row = 0; row < nrows; row++) {
        ds4_row_planar3 *out = (ds4_row_planar3 *)((char *)dst + row * sizeof(ds4_row_planar3));
        total += ds4_planar3_quantize_row(src + row * n_per_row, out);
    }
    return total;
}

void ds4_planar3_dequantize(const void *src, float *dst,
                              size_t nrows, size_t n_per_row) {
    assert(n_per_row == 512);
    for (size_t row = 0; row < nrows; row++) {
        const ds4_row_planar3 *in = (const ds4_row_planar3 *)
            ((const char *)src + row * sizeof(ds4_row_planar3));
        ds4_planar3_dequantize_row(in, dst + row * n_per_row);
    }
}

float ds4_planar3_roundtrip_cosine(const float *original, float *reconstructed,
                                    size_t dim) {
    float dot = 0.0f, n1 = 0.0f, n2 = 0.0f;
    for (size_t i = 0; i < dim; i++) {
        dot += original[i] * reconstructed[i];
        n1  += original[i] * original[i];
        n2  += reconstructed[i] * reconstructed[i];
    }
    float denom = sqrtf(n1) * sqrtf(n2);
    return (denom > 1e-10f) ? dot / denom : 0.0f;
}

float ds4_planar3_roundtrip_mse(const float *original, float *reconstructed,
                                  size_t dim) {
    float mse = 0.0f;
    for (size_t i = 0; i < dim; i++) {
        float d = original[i] - reconstructed[i];
        mse += d * d;
    }
    return mse / (float)dim;
}
